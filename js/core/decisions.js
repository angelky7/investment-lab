export function findScenario(id) {
  return SCENARIOS.find((s) => s.id === id) || null;
}

/**
 * 根据用户的每次选择推断「风格标签」。
 * 这不是评分——它只是把三条常见路径的倾向可视化，让人看到自己的模式。
 */
export const TONE_ORDER = ["纪律", "保守", "折中", "回避", "乐观", "投机", "追高", "锚定"];

export function summarizePath(choices) {
  const counts = {};
  for (const tone of choices) {
    counts[tone] = (counts[tone] || 0) + 1;
  }
  const ranked = Object.entries(counts).sort((a, b) => b[1] - a[1]);
  const dominant = ranked[0]?.[0] || "";
  const disciplined = (counts["纪律"] || 0) > choices.length / 2;
  return { counts, ranked, dominant, disciplined };
}